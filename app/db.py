import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path

DB_PATH = Path(__file__).resolve().parent.parent / "data" / "jobs.db"


class DatabaseConnection:
    def __init__(self, connection, postgres=False):
        self.connection = connection
        self.postgres = postgres

    def execute(self, query, parameters=()):
        if self.postgres:
            query = query.replace("?", "%s")
        return self.connection.execute(query, parameters)

    def executemany(self, query, parameters):
        if self.postgres:
            query = query.replace("?", "%s")
            cursor = self.connection.cursor()
            cursor.executemany(query, parameters)
            return cursor
        return self.connection.executemany(query, parameters)


def uses_postgres():
    return bool(os.environ.get("DATABASE_URL"))


@contextmanager
def connect():
    database_url = os.environ.get("DATABASE_URL")
    if database_url:
        import psycopg
        from psycopg.rows import dict_row

        conn = psycopg.connect(database_url, row_factory=dict_row)
        db = DatabaseConnection(conn, postgres=True)
    else:
        if os.environ.get("VERCEL"):
            raise RuntimeError(
                "Set DATABASE_URL to a managed PostgreSQL database on Vercel."
            )
        DB_PATH.parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(DB_PATH)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
        db = DatabaseConnection(conn)

    try:
        with conn:
            yield db
    finally:
        conn.close()


def init_db():
    if uses_postgres():
        _init_postgres()
    else:
        _init_sqlite()


def _init_postgres():
    schema = (
        """CREATE TABLE IF NOT EXISTS users (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          email TEXT NOT NULL UNIQUE,
          password_hash TEXT NOT NULL,
          created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS profiles (
          user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
          resume_name TEXT, resume_text TEXT, skills TEXT, consent INTEGER DEFAULT 0,
          updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS jobs (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          title TEXT NOT NULL, company TEXT NOT NULL, location TEXT, job_type TEXT,
          experience TEXT, remote INTEGER DEFAULT 0, description TEXT NOT NULL,
          skills TEXT NOT NULL, url TEXT, source TEXT DEFAULT 'Sample dataset'
        )""",
        """CREATE TABLE IF NOT EXISTS interactions (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
          action TEXT NOT NULL,
          created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        )""",
    )
    with connect() as db:
        for statement in schema:
            db.execute(statement)
        db.execute(
            "CREATE INDEX IF NOT EXISTS interactions_user_action "
            "ON interactions(user_id, action)"
        )
        _seed_jobs(db)


def _init_sqlite():
    schema = (
        """CREATE TABLE IF NOT EXISTS users (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          email TEXT NOT NULL UNIQUE COLLATE NOCASE,
          password_hash TEXT NOT NULL,
          created_at TEXT DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS profiles (
          user_id INTEGER PRIMARY KEY,
          resume_name TEXT, resume_text TEXT, skills TEXT, consent INTEGER DEFAULT 0,
          updated_at TEXT DEFAULT CURRENT_TIMESTAMP,
          FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        )""",
        """CREATE TABLE IF NOT EXISTS jobs (
          id INTEGER PRIMARY KEY, title TEXT NOT NULL, company TEXT NOT NULL,
          location TEXT, job_type TEXT, experience TEXT, remote INTEGER DEFAULT 0,
          description TEXT NOT NULL, skills TEXT NOT NULL, url TEXT,
          source TEXT DEFAULT 'Sample dataset'
        )""",
        """CREATE TABLE IF NOT EXISTS profile (
          id INTEGER PRIMARY KEY CHECK(id=1), resume_name TEXT, resume_text TEXT,
          skills TEXT, consent INTEGER DEFAULT 0, updated_at TEXT DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS interactions (
          id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL,
          job_id INTEGER NOT NULL, action TEXT NOT NULL,
          created_at TEXT DEFAULT CURRENT_TIMESTAMP,
          FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
          FOREIGN KEY(job_id) REFERENCES jobs(id) ON DELETE CASCADE
        )""",
    )
    with connect() as db:
        for statement in schema:
            db.execute(statement)
        interaction_columns = {
            row["name"] for row in db.execute("PRAGMA table_info(interactions)")
        }
        if "user_id" not in interaction_columns:
            db.execute(
                "ALTER TABLE interactions ADD COLUMN "
                "user_id INTEGER REFERENCES users(id) ON DELETE CASCADE"
            )
        db.execute(
            "CREATE INDEX IF NOT EXISTS interactions_user_action "
            "ON interactions(user_id, action)"
        )
        _seed_jobs(db)


def _seed_jobs(db):
    if db.execute("SELECT COUNT(*) AS count FROM jobs").fetchone()["count"] == 0:
        from .seed import JOBS

        db.executemany(
            """INSERT INTO jobs
               (title, company, location, job_type, experience, remote,
                description, skills, url)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
            JOBS,
        )
